-- V150: Create Front CMS Settings Table

CREATE TABLE IF NOT EXISTS cms_settings (
    id BIGSERIAL PRIMARY KEY,
    school_id BIGINT,
    website_logo TEXT,
    fav_icon TEXT,
    contact_email VARCHAR(255),
    complain_email VARCHAR(255),
    footer_text TEXT,
    school_app_enabled BOOLEAN DEFAULT TRUE,
    front_website_enabled BOOLEAN DEFAULT TRUE,
    school_tour_video_url TEXT,
    app_download_link TEXT,
    ios_app_link TEXT,
    theme_primary_color VARCHAR(50),
    theme_standard_color VARCHAR(50),
    google_analytics TEXT,
    welcome_popup_title VARCHAR(255),
    welcome_popup_image TEXT,
    facebook_url VARCHAR(500),
    instagram_url VARCHAR(500),
    whatsapp_url VARCHAR(500),
    x_url VARCHAR(500),
    linkedin_url VARCHAR(500),
    youtube_url VARCHAR(500),
    about_title VARCHAR(255),
    about_description TEXT,
    about_image TEXT,
    mission_title VARCHAR(255),
    mission_description TEXT,
    mission_image TEXT,
    vision_title VARCHAR(255),
    vision_description TEXT,
    vision_image TEXT,
    meta_description TEXT,
    meta_title VARCHAR(255),
    meta_keywords VARCHAR(500),
    og_title VARCHAR(255),
    og_description TEXT,
    og_image_url TEXT,
    og_url VARCHAR(500),
    og_type VARCHAR(100),
    active_theme_id INT DEFAULT 1,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_cms_settings_school ON cms_settings(school_id);

